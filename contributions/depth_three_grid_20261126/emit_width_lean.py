#!/usr/bin/env python3
"""Emit proof inputs and kernel checks; this program is not a proof oracle."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def rat(value):
    numerator, denominator = value
    return f'({numerator} / {denominator} : Rat)'


def bounds(value):
    lo, hi = value
    return f'⟨{rat(lo)}, {rat(hi)}⟩'


def main():
    rows = json.loads((HERE / 'data.json').read_text())['rows']
    lines = [
        'import DepthThreeGrid',
        'import DepthThreeWidth',
        '',
        '/-! Kernel-checked rational envelope witnesses for every depth-three word.',
        'Generated by contributions/depth_three_grid_20261126/emit_width_lean.py.',
        'The generator is untrusted; Lean recomputes every certificate predicate. -/',
        '',
        'namespace LoopsFormal.DepthThreeGrid',
        '',
        'open LoopsFormal.DepthThree',
        '',
        'set_option maxRecDepth 100000',
        'set_option maxHeartbeats 0',
        '',
    ]
    keys = []
    for row in rows:
        key = ''.join(map(str, row['word']))
        keys.append(key)
        w = row['width']
        lines.extend([
            f'def width{key} : WidthWitness where',
            f'  logV := {rat(w["log_v"])}',
            f'  angleA := {bounds(w["angles"][0])}',
            f'  angleB := {bounds(w["angles"][1])}',
            f'  complement := {bounds(w["complement"])}',
        ])
        for field, source in [('agmKLo', 'klo'), ('agmKHi', 'khi'),
                              ('agmSLo', 'slo'), ('agmSHi', 'shi')]:
            lines.append(f'  {field} := [' + ',\n    '.join(map(bounds, w['agm'][source])) + ']')
        lines.extend([
            '',
            f'theorem width{key}_certified : WidthCertificate gridScale packet{key} width{key} := by',
            '  decide +kernel',
            '',
        ])
    lines.extend([
        'def gridWidths : List (Packet × WidthWitness) := [',
        '  ' + ',\n  '.join(f'(packet{k}, width{k})' for k in keys) + ']',
        '',
        'theorem width_packets_are_complete : gridWidths.map Prod.fst = gridPackets := by',
        '  rfl',
        '',
        'theorem all_width_certificates (v : Packet × WidthWitness) (hv : v ∈ gridWidths) :',
        '    WidthCertificate gridScale v.1 v.2 := by',
        '  simp only [gridWidths, List.mem_cons, List.not_mem_nil, or_false] at hv',
        '  rcases hv with ' + ' | '.join(['rfl'] * len(keys)),
    ])
    for k in keys:
        lines.append(f'  · exact width{k}_certified')
    lines.extend([
        '',
        'theorem every_grid_packet_has_width_certificate (P : Packet) (hP : P ∈ gridPackets) :',
        '    ∃ w : WidthWitness, WidthCertificate gridScale P w := by',
        '  rw [← width_packets_are_complete] at hP',
        '  obtain ⟨v, hv, heq⟩ := List.mem_map.mp hP',
        '  exact ⟨v.2, heq ▸ all_width_certificates v hv⟩',
        '',
        '#print axioms all_width_certificates',
        '#print axioms every_grid_packet_has_width_certificate',
        '',
        'end LoopsFormal.DepthThreeGrid',
    ])
    (ROOT / 'DepthThreeWidthGrid.lean').write_text('\n'.join(lines) + '\n')
    print(f'Emitted {len(rows)} rational witness packets and kernel proofs.')


if __name__ == '__main__':
    main()

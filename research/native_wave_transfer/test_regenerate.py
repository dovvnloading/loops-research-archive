"""Independent oracle and adversarial mutations for the source-locked laboratory."""
from __future__ import annotations

import copy
import unittest
from pathlib import Path

import regenerate as lab


# A tiny local fixture exercises the independent algorithm without needing
# the legacy checker. Integration/lock checks use the real repository files.
SOURCE = {
    "parameter_bracket": {"denominator_power_of_two":128,
        "lower_numerator":-607918036626757496169199575185708826140,
        "upper_numerator":-607918036626757496169199575185708826139},
    "exact_orbit_relations":["x18=-x9"],
    "inner_root_exact_interval":"[x9,x18]",
    "phase_intervals_pairwise_disjoint":True,
    "phase_intervals":[{"physical_phase":k,"coarse_phase":0,"exact_interval":interval}
                       for k,interval in ((0,"[x9,x18]"),(3,"[x12,x3]"),(6,"[x6,x15]"))]
}


class IndependentRegeneratorTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.example = lab.load(lab.INPUT)
        cls.actual = lab.recompute(cls.example, SOURCE)

    def test_physical_oracle(self):
        a = self.actual
        self.assertEqual(a["ideal_boundary"]["target_atom_count"],10)
        self.assertEqual(a["ideal_boundary"]["covering_source_atom_count"],20)
        self.assertEqual(a["ideal_boundary"]["source_real_cuts"],
            ["-x12","x6","x15","-alpha","x9","x18","alpha","-x15","-x6","x12"])
        self.assertEqual(a["attachment_census"]["components"],
            [{"interval":"[-x3,x6)","root":"x6","boundary_atoms":[19,0,1],
              "immersion_boundary_destination":"target_interior_not_I0_boundary"}])
        g=a["operations"]["covering_f_star"]
        i=a["operations"]["immersion_iota_star"]
        self.assertEqual(g["source_to_target"],list(range(10))*2)
        self.assertEqual(i["block_lengths"],[5,2,1,1,3,1,3,1,1,2])
        self.assertNotEqual(g["source_to_target"],i["source_to_pullback"])
        self.assertEqual(a["sheet_paths"]["counts"],[2,1])
        self.assertEqual(a["sheet_paths"]["instances"]["crossing"]["source_restrictions"],
                         [[3,1],[19,17]])
        self.assertEqual(a["sheet_paths"]["instances"]["avoiding"]["source_restrictions"],[[3,17]])
        self.assertEqual(a["wave"]["target_width"],"log(4/3)/(2*pi)")
        self.assertEqual(a["wave"]["each_child_and_pushed_width"],"log(4/3)/pi")
        self.assertTrue(a["wave"]["harmonic_series_equality"])

    def test_changed_physical_return_fails(self):
        example=copy.deepcopy(self.example)
        example["return"]["physical_iterate"]=9
        with self.assertRaisesRegex(AssertionError,"return time"):
            lab.recompute(example,SOURCE)

    def test_conflated_actions_fail(self):
        example=copy.deepcopy(self.example)
        example["operations"]["immersion"]["ideal_action"]="f_*"
        with self.assertRaisesRegex(AssertionError,"wrong immersion"):
            lab.recompute(example,SOURCE)

    def test_moved_cut_fails(self):
        example=copy.deepcopy(self.example)
        example["marking"]["target_cuts"][2]="x9"
        with self.assertRaisesRegex(AssertionError,"marking source convention drift"):
            lab.recompute(example,SOURCE)

    def test_broken_wave_range_fails(self):
        example=copy.deepcopy(self.example)
        example["wave"]["open_radii"][1]="1/32"
        with self.assertRaises(AssertionError):
            lab.recompute(example,SOURCE)

    def test_fake_disk_certificate_fails(self):
        example=copy.deepcopy(self.example)
        example["paths"][0]["disk_limit"]="1/1000"
        with self.assertRaisesRegex(AssertionError,"whole complex disk"):
            lab.recompute(example,SOURCE)

    def test_bad_alpha_bracket_or_parameter_fails(self):
        source=copy.deepcopy(SOURCE)
        source["parameter_bracket"]["upper_numerator"] += 2**120
        with self.assertRaises(AssertionError):
            lab.recompute(self.example,source)

